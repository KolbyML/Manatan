import {readFile,writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const locales=JSON.parse(await readFile(path.join(root,'scripts/readme-locales.json'),'utf8'));
const names={en:'English','zh-CN':'简体中文','zh-Hant':'繁體中文',ja:'日本語',ko:'한국어',es:'Español',fr:'Français',de:'Deutsch','pt-BR':'Português',ru:'Русский',vi:'Tiếng Việt',th:'ภาษาไทย',id:'Bahasa Indonesia',it:'Italiano',nl:'Nederlands',tr:'Türkçe',ar:'العربية'};
const urls={download:'https://manatan.com/download',discord:'https://discord.gg/tDAtpPN8KK',releases:'https://github.com/KolbyML/Manatan/releases/latest',appStore:'https://apps.apple.com/app/manatan/id6756917436',flatpak:'https://kolbyml.github.io/Manatan/',guide:'https://manatan.com/blog/getting-started-manatan',docs:'https://manatan.com/docs',troubleshooting:'https://manatan.com/docs/guides/troubleshooting',plans:'https://manatan.com/support',issues:'https://github.com/KolbyML/Manatan/issues'};
const projects='- [Suwayomi Server](https://github.com/Suwayomi/Suwayomi-Server)\n- [Suwayomi WebUI](https://github.com/Suwayomi/Suwayomi-WebUI)\n- [hoshidicts](https://github.com/Manhhao/hoshidicts/tree/main-mit)';
const link=(text,url)=>`[${text}](${url})`;
const attribute=(text)=>text.replaceAll('&','&amp;').replaceAll('"','&quot;');
const badge=(label,color,url)=>link(`![${label}](https://img.shields.io/badge/${encodeURIComponent(label).replaceAll('-','--')}-${color}?style=for-the-badge)`,url);
function substitute(value,values){return value.replace(/\{(\w+)\}/g,(_,key)=>{if(!(key in values))throw Error(`Unknown substitution: ${key}`);return values[key];});}

function render(code,t){
  const prefix=code==='en'?'':'../../';
  const local=(file)=>prefix+file;
  const languages=Object.entries(names).map(([key,name])=>key===code?`**${name}**`:link(name,key==='en'?local('README.md'):(code==='en'?`docs/readme/README.${key}.md`:`README.${key}.md`))).join(' | ');
  // Shields' letter-spaced badge text breaks Arabic shaping. Native text keeps it readable.
  const actions=code==='ar'?`**${link(t.download,urls.download)}** · **${link(t.discord,urls.discord)}**`:`${badge(t.download,'1f883d',urls.download)} ${badge(t.discord,'5865f2',urls.discord)}`;
  const screenshot=(name,width,alt)=>`<a href="${local(`docs/assets/screenshots/dark/${name}.png`)}"><img src="${local(`docs/assets/screenshots/readme/${name}.webp`)}" width="${width}" alt="${attribute(alt)}"></a>`;
  const body=`<!-- Generated by scripts/build-readmes.mjs. Edit scripts/readme-locales.json, then regenerate. -->
<div align="center"${code==='ar'?' dir="rtl"':''}>

<img src="${local('docs/assets/screenshots/readme/logo.png')}" width="72" alt="Manatan">

<h1>Manatan</h1>
<h3>${t.tagline}</h3>

${t.intro}

[![${t.badgeAlt}](https://img.shields.io/badge/platform-Android%20%7C%20Windows%20%7C%20macOS%20%7C%20iOS%20%7C%20Linux%20%7C%20Web-lightgrey)](${urls.download})

${languages}

${actions}

${link(t.website,'https://manatan.com')} · ${link(t.guideLabel,urls.guide)} · ${link(t.docs,urls.docs)}

</div>
${code==='ar'?'\n<div dir="rtl">\n':''}
<p align="center">
  ${screenshot('video',900,t.videoAlt)}
</p>

<p align="center"><em>${t.caption}</em></p>

## ${t.featuresTitle}

- ${t.watch}
- ${t.lookup}
- ${t.remember}

## ${t.downloadTitle}

| ${t.platform} | ${t.get} | ${t.notes} |
| --- | --- | --- |
| Windows | ${link(t.installer,urls.download)} | x64 |
| macOS | ${link(t.macApp,urls.download)} | Apple Silicon / Intel |
| Linux | ${link('DEB',urls.download)} · ${link('Flatpak',urls.flatpak)} | AMD64 / ARM64 |
| Android | ${link('APK',urls.download)} | ARM64 |
| iPhone / iPad | ${link('App Store',urls.appStore)} · ${link('TestFlight',urls.discord)} | ${t.iosNote} |
| Web | [Manatan Tracker](https://manatan.com/account/lists) · [SRS](https://manatan.com/srs/) · ${link(t.webTools,'https://manatan.com/japanese-learning-resources')} | ${t.webNote} |

${substitute(t.betaNote,{discord:link(t.discord,urls.discord)})}

${substitute(t.releaseNote,{releases:link('GitHub Releases',urls.releases)})}

## ${t.startTitle}

1. ${t.step1}
2. ${t.step2}
3. ${t.step3}

${link(t.guideLabel,urls.guide)} · [AnkiConnect](https://manatan.com/blog/connect-manatan-anki-ankiconnect)

*${t.guideNote}*

## ${t.screensTitle}

<p align="center">
  ${screenshot('lookup',220,'Manatan: JMdict / EPUB')}
  ${screenshot('manga',220,'Manatan: Pepper & Carrot / OCR')}
  ${screenshot('books',220,'Manatan: EPUB')}
</p>
<p align="center">
  ${screenshot('podcasts',220,'Manatan: Nihongo con Teppei')}
  ${screenshot('video-library',220,'Manatan: Big Buck Bunny')}
</p>

${t.screensCaption} ${link(t.credits,local('docs/assets/screenshots/dark/CREDITS.txt'))}.

## ${t.helpTitle}

${link(t.docs,urls.docs)} · ${link(t.troubleshooting,urls.troubleshooting)} · ${link(t.issues,urls.issues)} · ${link(t.support,urls.plans)}

## ${t.thanks}

${projects}

${link(t.license,local('LICENSE'))} · ${link(t.credits,local('docs/assets/screenshots/dark/CREDITS.txt'))}

## ${t.starHistory}

[![${t.starHistory}](https://api.star-history.com/svg?repos=KolbyML/Manatan&type=date&legend=top-left)](https://www.star-history.com/#KolbyML/Manatan&type=date&legend=top-left)
${code==='ar'?'\n</div>\n':''}`;
  return body;
}

const keys=Object.keys(locales.en).sort();
let errors=0;
for(const code of Object.keys(names)){
  const t=locales[code];
  if(!t||JSON.stringify(Object.keys(t).sort())!==JSON.stringify(keys))throw Error(`Incomplete translation: ${code}`);
  for(const [key,value] of Object.entries(t)){
    if(typeof value!=='string'||!value.trim()||/[<>|\n]/.test(value))throw Error(`Invalid translation ${code}.${key}`);
  }
  for(const [key,token] of [['betaNote','discord'],['releaseNote','releases']])if(!t[key].includes(`{${token}}`))throw Error(`Missing ${token} in ${code}.${key}`);
  const file=path.join(root,code==='en'?'README.md':`docs/readme/README.${code}.md`);
  const content=render(code,t);
  if(process.argv.includes('--check')){
    const existing=await readFile(file,'utf8').catch(()=>null);
    if(existing!==content){console.error(`Out of date: ${path.relative(root,file)}`);errors++;}
  }else{await mkdir(path.dirname(file),{recursive:true});await writeFile(file,content);}
}
if(errors)process.exitCode=1;
else console.log(`${process.argv.includes('--check')?'Checked':'Generated'} ${Object.keys(names).length} synchronized READMEs.`);
